"""Generate it9175/tables.py and it9175/firmware.py from OpenDTV's Java tables.

The Java sources keep some values as AndroidX constants (the decompiler preserved
the symbolic names), so this script resolves those constants explicitly and then
evaluates the array literals. Run it whenever the Java reference changes:

    python tools/gen_tables.py [--source <dir with It9175Data.java>]

Defaults to the OpenDTVmod windows-driver copy on this machine.
"""
import argparse
import ast
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_SOURCE = os.environ.get(
    "OPENDTV_SOURCE",
    os.path.join(os.path.dirname(ROOT), "OpenDTVmod", "windows-driver",
                 "it9175", "src", "ph", "opendtv", "source"))

# AndroidX constants referenced by the decompiled tables, resolved from the
# library sources bundled in the same extraction.
CONSTANTS = {
    "MAX_RATE_BYTES_PER_SECOND": 40000,     # androidx.media3.extractor.MpegAudioUtil
    "VIDEO_STREAM_MASK": 240,              # androidx.media3.extractor.ts.PsExtractor
    "AUDIO_STREAM": 192,                   # androidx.media3.extractor.ts.PsExtractor
    "QUALITY_LOW_POWER": 104,              # androidx.core.location.LocationRequestCompat
    "DECODER_SUPPORT_MASK": 384,           # androidx.media3.exoplayer.RendererCapabilities
    "TS_PACKET_SIZE": 188,                 # androidx.media3.extractor.ts.TsExtractor
    "TS_STREAM_TYPE_HDMV_DTS": 130,
    "TS_STREAM_TYPE_SPLICE_INFO": 134,
    "TS_STREAM_TYPE_E_AC3": 135,
    "TS_STREAM_TYPE_DTS_HD": 136,
    "TS_STREAM_TYPE_AC4": 172,
    "DEFAULT_DETACH_SURFACE_TIMEOUT_MS": 2000,   # androidx.media3.exoplayer.ExoPlayer
    "DEFAULT_DURATION_TO_PROGRESS_US": 10000,    # androidx.media3.exoplayer.Renderer
}

STRING_ARRAYS = ["INIT_A0", "INIT_A1", "INIT_B0", "INIT_B1", "TUNE_PRE0", "TUNE_PRE1"]
INT_MATRICES = ["BANDS0", "BANDS1"]


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


QUALIFIERS = ("MpegAudioUtil", "LocationRequestCompat", "TsExtractor", "PsExtractor",
              "RendererCapabilities", "ExoPlayer", "Renderer")


def substitute(text):
    for cls in QUALIFIERS:
        text = re.sub(r"\b%s\." % cls, "", text)
    for name, value in CONSTANTS.items():
        text = re.sub(r"\b%s\b" % re.escape(name), str(value), text)
    left = sorted(set(re.findall(r"\b[A-Z][A-Z0-9_]{2,}\b", text)))
    unknown = [n for n in left if n not in CONSTANTS]
    if unknown:
        raise SystemExit("unresolved identifiers: %s" % ", ".join(unknown))
    return text


def find_array(text, name, kind):
    if kind == "string":
        pat = r"static final String\[\] %s = \{(.*?)\};" % name
    else:
        pat = r"static final int\[\]\[\] %s = \{(.*?)\};" % name
    m = re.search(pat, text, re.S)
    if not m:
        raise SystemExit("array %s not found" % name)
    return m.group(1)


def parse_strings(body):
    body = substitute(body)
    return ast.literal_eval("[" + body + "]")


def parse_matrix(body):
    body = substitute(body)
    body = body.replace("new int[]{", "[").replace("{", "[").replace("}", "]")
    body = re.sub(r"(\d+)[lL]\b", r"\1", body)
    return ast.literal_eval("[" + body + "]")


def parse_firmware(text):
    m = re.search(r"int\[\] CHUNKS = \{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit("CHUNKS not found")
    chunks = [int(x.strip()) for x in m.group(1).split(",") if x.strip()]
    m = re.search(r'String HEX = "(.*?)";', text, re.S)
    if not m:
        raise SystemExit("HEX not found")
    hexstr = re.sub(r"\s+", "", m.group(1))
    image = bytes.fromhex(hexstr)
    if sum(chunks) != len(image):
        raise SystemExit("chunk sum %d != image %d" % (sum(chunks), len(image)))
    return chunks, image


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", default=DEFAULT_SOURCE)
    args = ap.parse_args()
    src = args.source
    data_java = read(os.path.join(src, "It9175Data.java"))
    fw_java = read(os.path.join(src, "It9175Firmware.java"))

    out = ["# Generated by tools/gen_tables.py -- do not edit by hand.\n"]
    for name in STRING_ARRAYS:
        arr = parse_strings(find_array(data_java, name, "string"))
        out.append("%s = %r\n" % (name, arr))
    for name in INT_MATRICES:
        mat = parse_matrix(find_array(data_java, name, "matrix"))
        out.append("%s = %r\n" % (name, mat))

    with open(os.path.join(ROOT, "it9175", "tables.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))

    chunks, image = parse_firmware(fw_java)
    with open(os.path.join(ROOT, "it9175", "firmware.bin"), "wb") as f:
        f.write(image)
    sha = hashlib.sha256(image).hexdigest()
    with open(os.path.join(ROOT, "it9175", "firmware.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/gen_tables.py -- do not edit by hand.\n")
        f.write("CHUNKS = %r\n" % (chunks,))
        f.write("SIZE = %d\nSHA256 = %r\n" % (len(image), sha))
        f.write("""
def image(path=None):
    import hashlib
    import os

    if path is None:
        path = os.environ.get("IT9175_FIRMWARE") or os.path.join(
            os.path.dirname(__file__), "firmware.bin")
    if not os.path.exists(path):
        raise FileNotFoundError(
            "IT9175 firmware not found at %s. The vendor image is not distributed "
            "with this project: extract it from the IT9175 app, then set "
            "IT9175_FIRMWARE or pass --firmware PATH." % path)
    with open(path, "rb") as f:
        data = f.read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("firmware at %s does not match the expected image" % path)
    return data
""")
    print("tables: %d strings arrays, %d matrices" % (len(STRING_ARRAYS), len(INT_MATRICES)))
    print("firmware: %d bytes, %d chunks, sha256 %s" % (len(image), len(chunks), sha))


if __name__ == "__main__":
    main()
